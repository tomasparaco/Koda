-- ---------------------------------------------------------------------
-- 1. CONFIGURACIÓN POR EDIFICIO
-- ---------------------------------------------------------------------
ALTER TABLE public.edificios
  ADD COLUMN IF NOT EXISTS moneda_cobro text NOT NULL DEFAULT 'USD',
  ADD COLUMN IF NOT EXISTS porcentaje_fondo_reserva numeric(5,2) NOT NULL DEFAULT 10;

DO $$ BEGIN
  ALTER TABLE public.edificios
    ADD CONSTRAINT edificios_moneda_cobro_chk CHECK (moneda_cobro IN ('USD', 'EUR'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  ALTER TABLE public.edificios
    ADD CONSTRAINT edificios_pct_fondo_chk CHECK (porcentaje_fondo_reserva >= 0 AND porcentaje_fondo_reserva <= 100);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;


-- ---------------------------------------------------------------------
-- 2. RECIBOS CON DESGLOSE
--    monto_total = monto_alicuota + fondo_reserva + monto_cargos - monto_creditos
--    tipo: 'mensual' (el recibo del mes) o 'extra' (un cargo cobrado de inmediato)
-- ---------------------------------------------------------------------
ALTER TABLE public.recibos
  ADD COLUMN IF NOT EXISTS monto_cargos   numeric(12,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS monto_creditos numeric(12,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS moneda         text          NOT NULL DEFAULT 'USD',
  ADD COLUMN IF NOT EXISTS tipo           text          NOT NULL DEFAULT 'mensual',
  ADD COLUMN IF NOT EXISTS concepto       text;


-- ---------------------------------------------------------------------
-- 3. AJUSTES: multas, cargos extra y devoluciones
--    Siempre se guarda UNA fila por apartamento. Si el ajuste fue para todo
--    el edificio, se reparte por alícuota y todas las filas comparten "grupo".
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ajustes (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_edificio text        NOT NULL REFERENCES public.edificios(codigo_edificio) ON UPDATE CASCADE ON DELETE CASCADE,
  id_propietario  bigint      NOT NULL REFERENCES public.propietarios(id_propietario) ON DELETE CASCADE,
  grupo           uuid,                                   -- mismo valor para un ajuste repartido en el edificio
  tipo            text        NOT NULL CHECK (tipo IN ('cargo', 'credito')),
  categoria       text        NOT NULL DEFAULT 'otro'
                  CHECK (categoria IN ('multa', 'alquiler_salon', 'gasto_extra', 'devolucion', 'otro')),
  concepto        text        NOT NULL,
  monto           numeric(12,2) NOT NULL CHECK (monto > 0),
  aplicar         text        NOT NULL DEFAULT 'proximo_recibo' CHECK (aplicar IN ('proximo_recibo', 'inmediato')),
  estado          text        NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'aplicado', 'anulado')),
  id_recibo       bigint      REFERENCES public.recibos(id_recibo) ON DELETE SET NULL,
  creado_por      uuid        DEFAULT auth.uid(),
  created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ajustes_edificio_estado_idx ON public.ajustes (codigo_edificio, estado);
CREATE INDEX IF NOT EXISTS ajustes_propietario_idx     ON public.ajustes (id_propietario);
CREATE INDEX IF NOT EXISTS ajustes_recibo_idx          ON public.ajustes (id_recibo);


-- ---------------------------------------------------------------------
-- 3b. NOTIFICACIONES: permitir avisos solo en la app (sin correo)
--     La función "notificar" (supabase/functions/notificar) envía un correo por
--     cada notificación nueva, salvo que enviar_correo = false.
-- ---------------------------------------------------------------------
ALTER TABLE public.notificaciones
  ADD COLUMN IF NOT EXISTS enviar_correo boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS correo_enviado_at timestamptz;


-- ---------------------------------------------------------------------
-- 4. ADMINISTRADORAS MULTI-EDIFICIO
--    Para dar acceso: insertar una fila por cada edificio que maneja.
--    Ejemplo (cambia el correo y los códigos):
--
--    INSERT INTO public.administradora_edificios (id_auth, codigo_edificio, nombre, correo)
--    SELECT u.id, e.codigo_edificio, 'Administradora XYZ', u.email
--    FROM auth.users u, public.edificios e
--    WHERE u.email = 'administradora@correo.com'
--      AND e.codigo_edificio IN ('EDIF-01', 'EDIF-02');
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.administradora_edificios (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_auth         uuid        NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  codigo_edificio text        NOT NULL REFERENCES public.edificios(codigo_edificio) ON UPDATE CASCADE ON DELETE CASCADE,
  nombre          text,
  correo          text,       -- a este correo le llegan los avisos dirigidos a la administración
  celular         text,       -- para los avisos por SMS/WhatsApp (próximamente)
  created_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (id_auth, codigo_edificio)
);


-- ---------------------------------------------------------------------
-- 5. FUNCIONES DE PERMISOS
--    SECURITY DEFINER para que funcionen aunque propietarios tenga RLS.
-- ---------------------------------------------------------------------

-- ¿El usuario actual pertenece al edificio (propietario, junta o administradora)?
CREATE OR REPLACE FUNCTION public.kuota_es_miembro(p_codigo text)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM public.propietarios WHERE id_auth = auth.uid() AND codigo_edificio = p_codigo)
      OR EXISTS (SELECT 1 FROM public.administradora_edificios WHERE id_auth = auth.uid() AND codigo_edificio = p_codigo);
$$;

-- ¿El usuario actual puede gestionar el edificio (junta de condominio o administradora)?
CREATE OR REPLACE FUNCTION public.kuota_es_gestor(p_codigo text)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM public.propietarios
                 WHERE id_auth = auth.uid() AND codigo_edificio = p_codigo AND rol = 'admin')
      OR EXISTS (SELECT 1 FROM public.administradora_edificios
                 WHERE id_auth = auth.uid() AND codigo_edificio = p_codigo);
$$;

-- ¿El usuario actual es administradora del edificio?
CREATE OR REPLACE FUNCTION public.kuota_es_administradora(p_codigo text)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM public.administradora_edificios
                 WHERE id_auth = auth.uid() AND codigo_edificio = p_codigo);
$$;

-- ¿El propietario (apartamento) pertenece al usuario actual?
CREATE OR REPLACE FUNCTION public.kuota_es_mi_propietario(p_id bigint)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM public.propietarios WHERE id_propietario = p_id AND id_auth = auth.uid());
$$;

GRANT EXECUTE ON FUNCTION public.kuota_es_mi_propietario(bigint) TO authenticated;
GRANT EXECUTE ON FUNCTION public.kuota_es_miembro(text)        TO authenticated;
GRANT EXECUTE ON FUNCTION public.kuota_es_gestor(text)         TO authenticated;
GRANT EXECUTE ON FUNCTION public.kuota_es_administradora(text) TO authenticated;


-- ---------------------------------------------------------------------
-- 6. RLS DE LAS TABLAS NUEVAS
-- ---------------------------------------------------------------------
ALTER TABLE public.ajustes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.administradora_edificios ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.ajustes TO authenticated;
GRANT SELECT ON public.administradora_edificios TO authenticated;

DROP POLICY IF EXISTS ajustes_select ON public.ajustes;
CREATE POLICY ajustes_select ON public.ajustes FOR SELECT TO authenticated
  USING (
    public.kuota_es_gestor(codigo_edificio)
    OR public.kuota_es_mi_propietario(id_propietario)
  );

DROP POLICY IF EXISTS ajustes_gestor_write ON public.ajustes;
CREATE POLICY ajustes_gestor_write ON public.ajustes FOR ALL TO authenticated
  USING (public.kuota_es_gestor(codigo_edificio))
  WITH CHECK (public.kuota_es_gestor(codigo_edificio));

DROP POLICY IF EXISTS admin_edif_select ON public.administradora_edificios;
CREATE POLICY admin_edif_select ON public.administradora_edificios FOR SELECT TO authenticated
  USING (id_auth = auth.uid() OR public.kuota_es_gestor(codigo_edificio));


-- ---------------------------------------------------------------------
-- 7. ACCESO DE LA ADMINISTRADORA A LAS TABLAS EXISTENTES
--    Solo tiene efecto en tablas que tengan RLS activado. Las políticas son
--    permisivas: AGREGAN acceso a la administradora, no le quitan nada a nadie.
-- ---------------------------------------------------------------------
DO $$
DECLARE
  t text;
BEGIN
  -- Tablas que tienen la columna codigo_edificio
  FOREACH t IN ARRAY ARRAY[
    'edificios', 'propietarios', 'gastos', 'notificaciones', 'comunicados', 'eventos',
    'encuestas', 'tickets', 'documentos_condominio', 'contactos_emergencia', 'cuentas_bancarias'
  ] LOOP
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = t AND column_name = 'codigo_edificio') THEN
      EXECUTE format('DROP POLICY IF EXISTS kuota_administradora_all ON public.%I', t);
      EXECUTE format(
        'CREATE POLICY kuota_administradora_all ON public.%I FOR ALL TO authenticated
           USING (public.kuota_es_administradora(codigo_edificio))
           WITH CHECK (public.kuota_es_administradora(codigo_edificio))', t);
    END IF;
  END LOOP;
END $$;

-- recibos: el edificio se obtiene a través del propietario
DROP POLICY IF EXISTS kuota_administradora_all ON public.recibos;
CREATE POLICY kuota_administradora_all ON public.recibos FOR ALL TO authenticated
  USING (EXISTS (SELECT 1 FROM public.propietarios p
                 WHERE p.id_propietario = recibos.id_propietario
                   AND public.kuota_es_administradora(p.codigo_edificio)))
  WITH CHECK (EXISTS (SELECT 1 FROM public.propietarios p
                      WHERE p.id_propietario = recibos.id_propietario
                        AND public.kuota_es_administradora(p.codigo_edificio)));

-- pagos: el edificio se obtiene a través del recibo → propietario
DROP POLICY IF EXISTS kuota_administradora_all ON public.pagos;
CREATE POLICY kuota_administradora_all ON public.pagos FOR ALL TO authenticated
  USING (EXISTS (SELECT 1 FROM public.recibos r JOIN public.propietarios p ON p.id_propietario = r.id_propietario
                 WHERE r.id_recibo = pagos.id_recibo
                   AND public.kuota_es_administradora(p.codigo_edificio)))
  WITH CHECK (EXISTS (SELECT 1 FROM public.recibos r JOIN public.propietarios p ON p.id_propietario = r.id_propietario
                      WHERE r.id_recibo = pagos.id_recibo
                        AND public.kuota_es_administradora(p.codigo_edificio)));


-- ---------------------------------------------------------------------
-- 8. REALTIME (opcional): que los ajustes también se actualicen en vivo
-- ---------------------------------------------------------------------
DO $$ BEGIN
  ALTER PUBLICATION supabase_realtime ADD TABLE public.ajustes;
EXCEPTION WHEN duplicate_object OR undefined_object THEN NULL; END $$;

