-- =====================================================================
-- KUOTA · Fondo de reserva con META FIJA (reemplaza el % mensual)
-- El fondo tiene una meta (ej. $1.000) y un saldo. Solo se cobra cuando se
-- usa dinero de él: en el siguiente recibo se repone lo que falte para llegar
-- a la meta, repartido por alícuota. Si el fondo está lleno, no se cobra nada.
-- Seguro de ejecutar más de una vez.
-- =====================================================================

-- 1. Meta y saldo por edificio (la columna porcentaje_fondo_reserva queda en desuso)
ALTER TABLE public.edificios
  ADD COLUMN IF NOT EXISTS fondo_reserva_meta  numeric(12,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS fondo_reserva_saldo numeric(12,2) NOT NULL DEFAULT 0;

DO $$ BEGIN
  ALTER TABLE public.edificios
    ADD CONSTRAINT edificios_fondo_valores_chk CHECK (fondo_reserva_meta >= 0 AND fondo_reserva_saldo >= 0);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

COMMENT ON COLUMN public.edificios.porcentaje_fondo_reserva IS 'EN DESUSO desde 2026-10-29: el fondo ahora usa fondo_reserva_meta / fondo_reserva_saldo';

-- 2. Historial de movimientos del fondo
--    monto con signo: uso = negativo, reposicion = positivo, ajuste = diferencia
CREATE TABLE IF NOT EXISTS public.fondo_reserva_movimientos (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_edificio text NOT NULL REFERENCES public.edificios(codigo_edificio) ON UPDATE CASCADE ON DELETE CASCADE,
  tipo            text NOT NULL CHECK (tipo IN ('uso', 'reposicion', 'ajuste')),
  monto           numeric(12,2) NOT NULL,
  saldo_resultante numeric(12,2) NOT NULL,
  concepto        text NOT NULL,
  creado_por      uuid DEFAULT auth.uid(),
  created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS fondo_mov_edificio_idx ON public.fondo_reserva_movimientos (codigo_edificio, created_at DESC);

ALTER TABLE public.fondo_reserva_movimientos ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.fondo_reserva_movimientos TO authenticated;

-- Todos los del edificio pueden ver el historial (transparencia); solo se escribe con las funciones
DROP POLICY IF EXISTS fondo_mov_select ON public.fondo_reserva_movimientos;
CREATE POLICY fondo_mov_select ON public.fondo_reserva_movimientos FOR SELECT TO authenticated
  USING (public.kuota_es_miembro(codigo_edificio));

-- 3. Funciones (atómicas: bloquean la fila del edificio mientras actualizan)

-- Configurar meta y saldo actual (junta o administradora)
CREATE OR REPLACE FUNCTION public.kuota_fondo_configurar(p_codigo text, p_meta numeric, p_saldo numeric)
RETURNS numeric LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_anterior numeric;
BEGIN
  IF NOT public.kuota_es_gestor(p_codigo) THEN RAISE EXCEPTION 'No tienes permiso para gestionar este edificio'; END IF;
  IF p_meta < 0 OR p_saldo < 0 THEN RAISE EXCEPTION 'La meta y el saldo no pueden ser negativos'; END IF;
  SELECT fondo_reserva_saldo INTO v_anterior FROM edificios WHERE codigo_edificio = p_codigo FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Edificio % no existe', p_codigo; END IF;
  UPDATE edificios SET fondo_reserva_meta = p_meta, fondo_reserva_saldo = p_saldo WHERE codigo_edificio = p_codigo;
  IF p_saldo <> v_anterior THEN
    INSERT INTO fondo_reserva_movimientos (codigo_edificio, tipo, monto, saldo_resultante, concepto)
    VALUES (p_codigo, 'ajuste', p_saldo - v_anterior, p_saldo, 'Saldo actualizado por la administración');
  END IF;
  RETURN p_saldo;
END $$;

-- Usar dinero del fondo
CREATE OR REPLACE FUNCTION public.kuota_fondo_usar(p_codigo text, p_monto numeric, p_concepto text)
RETURNS numeric LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_saldo numeric;
BEGIN
  IF NOT public.kuota_es_gestor(p_codigo) THEN RAISE EXCEPTION 'No tienes permiso para gestionar este edificio'; END IF;
  IF p_monto IS NULL OR p_monto <= 0 THEN RAISE EXCEPTION 'El monto debe ser mayor a 0'; END IF;
  IF coalesce(trim(p_concepto), '') = '' THEN RAISE EXCEPTION 'Escribe en qué se usó el dinero'; END IF;
  SELECT fondo_reserva_saldo INTO v_saldo FROM edificios WHERE codigo_edificio = p_codigo FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Edificio % no existe', p_codigo; END IF;
  IF p_monto > v_saldo THEN RAISE EXCEPTION 'El fondo solo tiene % disponible', v_saldo; END IF;
  UPDATE edificios SET fondo_reserva_saldo = v_saldo - p_monto WHERE codigo_edificio = p_codigo;
  INSERT INTO fondo_reserva_movimientos (codigo_edificio, tipo, monto, saldo_resultante, concepto)
  VALUES (p_codigo, 'uso', -p_monto, v_saldo - p_monto, trim(p_concepto));
  RETURN v_saldo - p_monto;
END $$;

-- Reponer el fondo (lo llama la emisión de recibos con lo que se facturó)
CREATE OR REPLACE FUNCTION public.kuota_fondo_reponer(p_codigo text, p_monto numeric, p_concepto text)
RETURNS numeric LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_saldo numeric; v_meta numeric; v_nuevo numeric;
BEGIN
  IF NOT public.kuota_es_gestor(p_codigo) THEN RAISE EXCEPTION 'No tienes permiso para gestionar este edificio'; END IF;
  IF p_monto IS NULL OR p_monto <= 0 THEN RETURN NULL; END IF;
  SELECT fondo_reserva_saldo, fondo_reserva_meta INTO v_saldo, v_meta FROM edificios WHERE codigo_edificio = p_codigo FOR UPDATE;
  v_nuevo := least(v_meta, v_saldo + p_monto);
  UPDATE edificios SET fondo_reserva_saldo = v_nuevo WHERE codigo_edificio = p_codigo;
  INSERT INTO fondo_reserva_movimientos (codigo_edificio, tipo, monto, saldo_resultante, concepto)
  VALUES (p_codigo, 'reposicion', v_nuevo - v_saldo, v_nuevo, p_concepto);
  RETURN v_nuevo;
END $$;

GRANT EXECUTE ON FUNCTION public.kuota_fondo_configurar(text, numeric, numeric) TO authenticated;
GRANT EXECUTE ON FUNCTION public.kuota_fondo_usar(text, numeric, text)          TO authenticated;
GRANT EXECUTE ON FUNCTION public.kuota_fondo_reponer(text, numeric, text)       TO authenticated;

